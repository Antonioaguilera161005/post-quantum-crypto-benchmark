from pathlib import Path

import pandas as pd


NETWORK_PATH = Path(
    "results/economic/cloud_network_cost.csv"
)

COMPUTE_PATH = Path(
    "results/economic/provider_compute_cost.csv"
)

OUTPUT_PATH = Path(
    "results/economic/total_operational_cost.csv"
)


PROVIDER_MAP = {
    "AWS-Spain-m7i.large": "AWS",
    "Azure-Spain-D2s_v5": "Azure",
    "GCP-Madrid-e2-standard-2": "GCP",

    "Azure-Europe-Premium": "Azure",
    "GCP-Madrid-Standard": "GCP",
}


def normalize_provider(name):
    return PROVIDER_MAP.get(name, name)


def main():

    network = pd.read_csv(NETWORK_PATH)
    compute = pd.read_csv(COMPUTE_PATH)

    network["provider_family"] = (
        network["provider"]
        .apply(normalize_provider)
    )

    compute["provider_family"] = (
        compute["provider"]
        .apply(normalize_provider)
    )

    merged = compute.merge(
        network,
        on=[
            "provider_family",
            "scenario",
            "algorithm",
            "handshakes_per_month",
        ],
        suffixes=(
            "_compute",
            "_network"
        ),
    )

    # ============================================================
    # STANDALONE SCENARIO
    #
    # Crypto traffic is treated as if it were the only
    # traffic generated by the cloud account.
    # Provider free allowances therefore apply.
    # ============================================================

    merged[
        "standalone_total_cost_month"
    ] = (
        merged["compute_cost_month"]
        + merged["standalone_network_cost"]
    )

    # ============================================================
    # MARGINAL / ENTERPRISE SCENARIO
    #
    # Assumes the normal infrastructure has already consumed
    # the provider's free network allowance.
    # ============================================================

    merged[
        "marginal_network_cost_month"
    ] = (
        merged["provider_traffic_units"]
        * merged["price_per_unit"]
    )

    merged[
        "marginal_total_cost_month"
    ] = (
        merged["compute_cost_month"]
        + merged["marginal_network_cost_month"]
    )

    # ============================================================
    # BASELINE DIFFERENCE
    # ============================================================

    merged[
        "extra_operational_cost_vs_classical"
    ] = 0.0

    for (
        provider,
        handshakes
    ), group in merged.groupby(
        [
            "provider_family",
            "handshakes_per_month",
        ]
    ):

        classical = group[
            group["scenario"] == "Classical"
        ].iloc[0]

        baseline = classical[
            "marginal_total_cost_month"
        ]

        indexes = group.index

        merged.loc[
            indexes,
            "extra_operational_cost_vs_classical"
        ] = (
            group[
                "marginal_total_cost_month"
            ]
            - baseline
        )

    merged[
        "extra_operational_cost_year"
    ] = (
        merged[
            "extra_operational_cost_vs_classical"
        ]
        * 12
    )

    OUTPUT_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    merged.to_csv(
        OUTPUT_PATH,
        index=False,
    )

    display = merged[
        merged["handshakes_per_month"]
        == 100_000_000
    ]

    print("=" * 130)
    print(
        " OPERATIONAL PQC COST — "
        "100 MILLION HANDSHAKES / MONTH"
    )
    print("=" * 130)

    columns = [
        "provider_family",
        "scenario",
        "algorithm",
        "standalone_total_cost_month",
        "marginal_total_cost_month",
        "extra_operational_cost_vs_classical",
        "extra_operational_cost_year",
    ]

    print(
        display[
            columns
        ].to_string(
            index=False,
            float_format=lambda x:
                f"{x:.4f}",
        )
    )

    print(
        f"\nResults saved to: "
        f"{OUTPUT_PATH}"
    )

    print(
        "\nStandalone:"
        "\n  Provider free network allowance applies."
        "\nMarginal:"
        "\n  Free allowance assumed already consumed "
        "by normal company traffic."
    )


if __name__ == "__main__":
    main()